import puppeteer from 'puppeteer-core';
import fs from 'fs'; import path from 'path'; import {pathToFileURL} from 'node:url';
const CHROME='C:/Program Files/Google/Chrome/Application/chrome.exe';
const b=await puppeteer.launch({executablePath:CHROME,headless:'new',args:['--no-sandbox','--allow-file-access-from-files']});
const p=await b.newPage();
const src=path.resolve('upsell-fonte/manual-confeiteira.png');
fs.writeFileSync('_u.html','<img id=i src="'+pathToFileURL(src).href+'"><canvas id=c></canvas>');
await p.goto(pathToFileURL(path.resolve('_u.html')).href,{waitUntil:'load'});
const antes=fs.statSync(src).size;
const r=await p.evaluate(async()=>{
  const im=document.getElementById('i'); await im.decode();
  const tw=900, sc=Math.min(1,tw/im.naturalWidth);
  const c=document.getElementById('c');
  c.width=Math.round(im.naturalWidth*sc); c.height=Math.round(im.naturalHeight*sc);
  const x=c.getContext('2d'); x.imageSmoothingQuality='high';
  x.drawImage(im,0,0,c.width,c.height);
  return {u:c.toDataURL('image/webp',0.82), w:c.width, h:c.height};
});
const buf=Buffer.from(r.u.split(',')[1],'base64');
fs.writeFileSync('../assets/img/manual-confeiteira.webp',buf);
console.log('manual-confeiteira.webp', r.w+'x'+r.h, (antes/1024|0)+'KB -> '+(buf.length/1024|0)+'KB');
await b.close();
